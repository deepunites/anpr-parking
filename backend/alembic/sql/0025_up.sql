-- Полные номера в панели: клиент (оператор ПДн) решает сам, показывать ли сотрудникам площадки номер целиком.
-- По умолчанию — маска (01A***AA). Включает администратор в «Площадках» (с причиной, в аудите). Хранение не меняется:
-- открытого номера по-прежнему нет ни в одной колонке, журналах, событиях и вебхуках (I-10).
ALTER TABLE parking_lot ADD COLUMN show_full_plates boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN parking_lot.show_full_plates IS 'Показывать сотрудникам площадки (владелец, администратор, менеджер, оператор, кассир) номер целиком, а не маской.';
